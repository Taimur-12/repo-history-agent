import json
import statistics
from pathlib import Path

import yaml

from harness.score import GOLDEN, ROOT, score

RESULTS = ROOT / "data" / "results"
RUNS = ROOT / "data" / "traces" / "runs.jsonl"


def load_records():
    records = {}
    for line in RUNS.read_text().splitlines():
        record = json.loads(line)
        records[record["run_id"]] = record
    return records


def summarise_file(path, cases, records):
    saved = json.loads(path.read_text())
    if not isinstance(saved, dict) or "runs" not in saved:
        return None
    runs = [r for r in saved["runs"] if r["run_id"] in records and r["case_id"] in cases]
    if not runs:
        return None
    traced = [records[r["run_id"]] for r in runs]
    graded = [score(cases[r["case_id"]], records[r["run_id"]]) for r in runs]
    meta = saved["meta"]
    return {
        "file": path.name,
        "date": meta["ran_at"][:10],
        "prompt": meta["prompt_version"] + (" + check" if meta.get("check") else ""),
        "model": meta["model"],
        "reasoning": meta.get("reasoning") or "default",
        "cases": len({r["case_id"] for r in runs}),
        "runs": len(runs),
        "passed": sum(g["passed"] for g in graded),
        "tokens": statistics.median(t["tokens_in"] + t["tokens_out"] for t in traced),
        "seconds": statistics.median(t["latency_ms"] / 1000 for t in traced),
        "calls": statistics.median(len(t["calls"]) for t in traced),
        "unseen": sum(len(g["stages"]["unseen_cites"]) for g in graded),
    }


def main():
    cases = {c["id"]: c for c in yaml.safe_load(GOLDEN.read_text())}
    records = load_records()
    rows = [row for path in sorted(RESULTS.glob("*.json")) if (row := summarise_file(path, cases, records))]
    print("# Saved eval runs, re-graded with the current grader")
    print()
    print("Generated by `python -m harness.summary > results/summary.md` from `data/results/` and `data/traces/runs.jsonl`.")
    print("Tokens are input plus output. Medians are per run. A run is one answer to one case.")
    print()
    print("| Date (UTC) | Prompt | Model | Reasoning | Cases | Runs | Passed | Median tokens | Median seconds | Median tool calls | Results file |")
    print("|---|---|---|---|---|---|---|---|---|---|---|")
    for row in rows:
        print(f"| {row['date']} | {row['prompt']} | {row['model']} | {row['reasoning']} | {row['cases']} | {row['runs']} | {row['passed']}/{row['runs']} "
              f"| {row['tokens']:,.0f} | {row['seconds']:.0f} | {row['calls']:.0f} | `{row['file']}` |")
    print()
    total = sum(row["runs"] for row in rows)
    print(f"{len(rows)} results files, {total} runs. Citations of a number that appears in no tool result: "
          f"{sum(row['unseen'] for row in rows)}.")


if __name__ == "__main__":
    main()
